#!/usr/bin/env node

/**
 * Interactive setup for Claude Code Remote — Slack + Tmux only
 * - Guides user through .env generation
 * - Merges required hooks into ~/.claude/settings.json
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const readline = require('readline');
const dotenv = require('dotenv');

const projectRoot = __dirname;
const envPath = path.join(projectRoot, '.env');
const hookScriptPath = path.join(projectRoot, 'claude-hook-notify.js');

const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout
});

function ask(question, defaultValue = '') {
    const suffix = defaultValue ? ` (${defaultValue})` : '';
    return new Promise(resolve => {
        rl.question(`  ${question}${suffix}: `, answer => {
            resolve(answer.trim() || defaultValue);
        });
    });
}

function askYesNo(question, defaultValue = false) {
    const suffix = defaultValue ? ' [Y/n]' : ' [y/N]';
    return new Promise(resolve => {
        rl.question(`  ${question}${suffix} `, answer => {
            const normalized = answer.trim().toLowerCase();
            if (!normalized) return resolve(defaultValue);
            resolve(normalized === 'y' || normalized === 'yes');
        });
    });
}

function loadExistingEnv() {
    if (!fs.existsSync(envPath)) return {};
    try {
        return dotenv.parse(fs.readFileSync(envPath, 'utf8'));
    } catch {
        return {};
    }
}

function serializeEnvValue(value) {
    if (value === undefined || value === null) return '';
    const s = String(value);
    if (s === '') return '';
    if (/[^\w@%/:.\-]/.test(s)) return `"${s.replace(/"/g, '\\"')}"`;
    return s;
}

function writeEnvFile(values, existingEnv) {
    const orderedKeys = [
        'SLACK_BOT_TOKEN', 'SLACK_APP_TOKEN', 'SLACK_CHANNEL_ID',
        'SLACK_REPO_PATH', 'SLACK_REPO_ROOT', 'SLACK_CLAUDE_COMMAND',
        'SLACK_WHITELIST', 'SLACK_HTTP_PORT',
        'LOG_LEVEL'
    ];

    const merged = { ...existingEnv, ...values };
    const lines = [
        '# Claude Code Remote configuration (Slack + Tmux)',
        `# Generated by setup.js on ${new Date().toISOString()}`,
        ''
    ];

    orderedKeys.forEach(key => {
        if (merged[key] === undefined) return;
        lines.push(`${key}=${serializeEnvValue(merged[key])}`);
    });

    const extras = Object.keys(merged).filter(k => !orderedKeys.includes(k));
    if (extras.length > 0) {
        lines.push('');
        lines.push('# User-defined / preserved keys');
        extras.forEach(key => {
            lines.push(`${key}=${serializeEnvValue(merged[key])}`);
        });
    }

    fs.writeFileSync(envPath, lines.join('\n') + '\n');
    return envPath;
}

function makeHookCommand(event) {
    const script = hookScriptPath.includes(' ') ? `"${hookScriptPath}"` : hookScriptPath;
    return `node ${script} ${event}`;
}

function ensureHooksFile() {
    const settingsDir = path.join(os.homedir(), '.claude');
    const settingsPath = path.join(settingsDir, 'settings.json');
    let settings = {};
    let existing = false;
    let backupPath = null;

    if (!fs.existsSync(settingsDir)) {
        fs.mkdirSync(settingsDir, { recursive: true });
    }

    if (fs.existsSync(settingsPath)) {
        existing = true;
        try {
            settings = JSON.parse(fs.readFileSync(settingsPath, 'utf8'));
        } catch {
            backupPath = `${settingsPath}.bak-${Date.now()}`;
            fs.copyFileSync(settingsPath, backupPath);
            settings = {};
        }
    }

    settings.hooks = settings.hooks || {};

    const stopHooks = Array.isArray(settings.hooks.Stop) ? settings.hooks.Stop : [];
    const subagentHooks = Array.isArray(settings.hooks.SubagentStop) ? settings.hooks.SubagentStop : [];

    const completedCommand = makeHookCommand('completed');
    const waitingCommand = makeHookCommand('waiting');

    function upsertHook(list, command) {
        const exists = list.some(entry =>
            Array.isArray(entry.hooks) && entry.hooks.some(h => h.command === command)
        );
        if (!exists) {
            list.push({
                matcher: '*',
                hooks: [{ type: 'command', command, timeout: 15 }]
            });
        }
        return list;
    }

    settings.hooks.Stop = upsertHook(stopHooks, completedCommand);
    settings.hooks.SubagentStop = upsertHook(subagentHooks, waitingCommand);

    fs.writeFileSync(settingsPath, JSON.stringify(settings, null, 2));

    return { settingsPath, existing, backupPath };
}

async function main() {
    console.log('\n' + '='.repeat(50));
    console.log('  Claude Code Remote - Setup (Slack + Tmux)');
    console.log('='.repeat(50) + '\n');

    const existingEnv = loadExistingEnv();

    console.log('  Slack Configuration\n');

    const botToken = await ask('Bot Token (xoxb-...)', existingEnv.SLACK_BOT_TOKEN || '');
    const appToken = await ask('App Token (xapp-...)', existingEnv.SLACK_APP_TOKEN || '');
    const channelId = await ask('Channel ID', existingEnv.SLACK_CHANNEL_ID || '');
    const repoPath = await ask('Default repo path', existingEnv.SLACK_REPO_PATH || '');
    const repoRoot = await ask('Repo root for project discovery (optional)', existingEnv.SLACK_REPO_ROOT || '');
    const claudeCommand = await ask('Claude command', existingEnv.SLACK_CLAUDE_COMMAND || 'claude --dangerously-skip-permissions');
    const whitelist = await ask('Whitelist user IDs (comma-separated, empty=all)', existingEnv.SLACK_WHITELIST || '');
    const httpPort = await ask('HTTP API port', existingEnv.SLACK_HTTP_PORT || '9999');

    console.log('\n  System Configuration\n');

    const logLevel = await ask('Log level (debug/info/warn/error)', existingEnv.LOG_LEVEL || 'info');

    const envValues = {
        SLACK_BOT_TOKEN: botToken,
        SLACK_APP_TOKEN: appToken,
        SLACK_CHANNEL_ID: channelId,
        SLACK_REPO_PATH: repoPath,
        SLACK_REPO_ROOT: repoRoot,
        SLACK_CLAUDE_COMMAND: claudeCommand,
        SLACK_WHITELIST: whitelist,
        SLACK_HTTP_PORT: httpPort,
        LOG_LEVEL: logLevel
    };

    console.log('\n  Saving...');
    const savedPath = writeEnvFile(envValues, existingEnv);
    console.log(`  .env saved to ${savedPath}`);

    const updateHooks = await askYesNo('Update ~/.claude/settings.json hooks?', true);
    if (updateHooks) {
        const { settingsPath, backupPath } = ensureHooksFile();
        if (backupPath) {
            console.log(`  Warning: backed up invalid settings to ${backupPath}`);
        }
        console.log(`  Hooks configured at ${settingsPath}`);
        console.log(`    Stop -> ${makeHookCommand('completed')}`);
        console.log(`    SubagentStop -> ${makeHookCommand('waiting')}`);
    }

    rl.close();

    console.log('\n' + '-'.repeat(50));
    console.log('  Setup complete! Next steps:');
    console.log('    1. npm run slack     (start Socket Mode)');
    console.log('    2. Start Claude in a tmux session');
    console.log('-'.repeat(50) + '\n');
}

main().catch(err => {
    console.error('Setup failed:', err.message);
    rl.close();
    process.exit(1);
});
